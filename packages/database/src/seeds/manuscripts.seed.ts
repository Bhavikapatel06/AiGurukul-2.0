export async function seedCanonicalManuscripts(): Promise<number> {
  const { ManuscriptModel } = await import('../models/manuscript.model.js');
  let count = 0;
  for (const m of CANONICAL_SEED_MANUSCRIPTS) {
    const existing = await ManuscriptModel.findOne({ slug: m.slug });
    if (!existing) {
      await ManuscriptModel.create({
        slug: m.slug,
        title: m.title,
        originalLanguage: m.originalLanguage,
        sourceScript: m.sourceScript,
        originalText: m.originalText,
        transliteration: m.transliteration,
        canonicalSource: m.canonicalSource,
        verseReference: m.verseReference,
        poeticMeter: m.poeticMeter,
        authorOrRishi: m.authorOrRishi,
        wordBreakdown: m.wordBreakdown,
        translations: m.translations,
      });
      count++;
    }
  }
  return count;
}
